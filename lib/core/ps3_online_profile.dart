enum Ps3OnlineIssue implements Exception { unqualified, storage, core, update, patch, firmware, account }

final _ps3TitleId = RegExp(r'^[A-Z]{4}[0-9]{5}$');
final _ps3ProviderId = RegExp(r'^[a-z0-9][a-z0-9-]{0,47}$');

Map<String, String>? _onlineDiscMetadata(String disc) {
  if (p.basename(disc).toUpperCase() != 'PS3_DISC.SFB') return null;
  final fields = Ps3Disc.metadata(p.dirname(disc));
  return _ps3TitleId.hasMatch(fields?['TITLE_ID'] ?? '') ? fields : null;
}

enum Ps3Xfloat { accurate, approximate, relaxed, inaccurate }

enum Ps3Dns {
  google('8.8.8.8'),
  cloudflare('1.1.1.1'),
  openDns('208.67.222.222');

  const Ps3Dns(this.address);
  final String address;
}

sealed class Ps3OnlineProtection {
  const Ps3OnlineProtection(this.sha256);
  final String sha256;
}

final class Ps3SprxProtection extends Ps3OnlineProtection {
  const Ps3SprxProtection(this.name, super.sha256);
  final String name;
}

final class Ps3YamlProtection extends Ps3OnlineProtection {
  const Ps3YamlProtection({required String sha256, required this.ppuHash, required this.patches, this.basePatchSha256})
    : super(sha256);

  final String ppuHash;

  /// Patch description and exact number of applied operations expected at boot.
  final Map<String, int> patches;

  /// Optional pin for the patch database generated by the reviewed core.
  final String? basePatchSha256;
}

/// Pins a reviewed provider and game revision to the exact launch artifacts.
/// The application supplies these records from its reviewed release catalog.
final class Ps3OnlineRelease {
  const Ps3OnlineRelease({
    required this.provider,
    required this.titleId,
    required this.updateVersion,
    this.updateTreeDigest,
    this.generatedUpdateFiles = const {},
    required this.coreSha256,
    required this.executableSha256,
    required this.protection,
    required this.rpcnHost,
    required this.providerFiles,
    required this.xfloat,
    required this.dns,
    required this.upnp,
  });

  /// Only releases qualified for an actual provider belong here.
  static const catalog = <Ps3OnlineRelease>[];

  final String provider;
  final String titleId;
  final String updateVersion;
  final String? updateTreeDigest;

  /// Exact paths created by the game after a verified launch, relative to the title directory.
  final Set<String> generatedUpdateFiles;
  final String coreSha256;
  final String executableSha256;
  final Ps3OnlineProtection protection;
  final String rpcnHost;

  /// Relative RPCS3 HDD paths and SHA-256 digests for public provider files.
  final Map<String, String> providerFiles;
  final Ps3Xfloat xfloat;
  final Ps3Dns dns;
  final bool upnp;

  bool get hasManagedProfile =>
      updateTreeDigest != null &&
      protection is Ps3YamlProtection &&
      _ps3ProviderId.hasMatch(provider) &&
      _ps3TitleId.hasMatch(titleId);
}

enum Ps3OnlineReadinessState { discUnavailable, noProvider, profileRequired }

/// Local library facts. A detected version is not a verified online profile.
final class Ps3OnlineReadiness {
  const Ps3OnlineReadiness._(this.state, {this.titleId, this.discVersion, this.managedUpdate});

  final Ps3OnlineReadinessState state;
  final String? titleId;
  final String? discVersion;
  final String? managedUpdate;

  static final _version = RegExp(r'^\d{2}\.\d{2}$');

  static Ps3OnlineReadiness inspect({
    required String disc,
    required String managedSystem,
    Iterable<Ps3OnlineRelease> releases = Ps3OnlineRelease.catalog,
  }) {
    final fields = _onlineDiscMetadata(disc);
    if (fields == null) return const Ps3OnlineReadiness._(Ps3OnlineReadinessState.discUnavailable);
    final title = fields['TITLE_ID']!;
    final update = p.join(managedSystem, 'rpcs3', 'dev_hdd0', 'game', title);
    final installed = File(p.join(update, 'USRDIR', 'EBOOT.BIN')).existsSync()
        ? Ps3Disc.readSfo(File(p.join(update, 'PARAM.SFO')))
        : null;
    return Ps3OnlineReadiness._(
      releases.any((release) => release.titleId == title)
          ? Ps3OnlineReadinessState.profileRequired
          : Ps3OnlineReadinessState.noProvider,
      titleId: title,
      discVersion: _applicationVersion(fields),
      managedUpdate: installed?['TITLE_ID'] == title ? _applicationVersion(installed!) : null,
    );
  }

  static String? _applicationVersion(Map<String, String> fields) {
    final version = fields['APP_VER'];
    return version != null && _version.hasMatch(version) ? version : null;
  }
}

/// Local launch capability. The account and provider configuration stay in the
/// isolated RPCS3 profile. The method channel receives network options and
/// required boot patch metadata.
final class Ps3OnlineProfile {
  const Ps3OnlineProfile._(
    this.release,
    this.disc,
    this.core,
    this.systemRoot,
    this.saveRoot,
    this._offlineSystemRoot,
    this._patchProtection,
  );

  final Ps3OnlineRelease release;
  final String disc;
  final String core;
  final String systemRoot;
  final String saveRoot;
  final String _offlineSystemRoot;
  final Map<String, Object>? _patchProtection;

  static Future<String> managedProfileRoot(String managedRoot, Ps3OnlineRelease release, {bool create = false}) async {
    if (!release.hasManagedProfile) throw Ps3OnlineIssue.unqualified;
    var root = await _directory(managedRoot);
    for (final name in ['OnlineProfiles', release.provider, release.titleId]) {
      root = await _managedDirectory(root, name, create: create);
    }
    return root;
  }

  static Future<bool> importProtection(
    String managedRoot,
    Ps3OnlineRelease release,
    String source, {
    required bool Function() canPublish,
  }) async {
    final protection = release.protection;
    if (!release.hasManagedProfile || protection is! Ps3YamlProtection) throw Ps3OnlineIssue.unqualified;
    final bytes = await _readProtection(File(source), protection.sha256);
    return _publishManagedFile(
      managedRoot,
      release,
      ['system', 'rpcs3', 'patches'],
      '${release.titleId}_patch.yml',
      canPublish,
      (file) async => file.writeAsBytes(bytes, flush: true),
    );
  }

  static Future<bool> importAccount(
    String managedRoot,
    Ps3OnlineRelease release,
    String source, {
    required bool Function() canPublish,
  }) async {
    if (!release.hasManagedProfile) throw Ps3OnlineIssue.unqualified;
    final account = await _readAccount(File(source), release.rpcnHost);
    return _publishManagedFile(
      managedRoot,
      release,
      ['system', 'rpcs3', if (Platform.isWindows) 'config'],
      'rpcn.yml',
      canPublish,
      (file) async => file.writeAsString(jsonEncode(account), flush: true),
    );
  }

  static Future<bool> prepareFirmware(
    ManagedRetro managed,
    Ps3OnlineRelease release, {
    required bool Function() canPublish,
    required void Function(int, int) progress,
  }) async {
    if (!canPublish()) return false;
    final profile = await managedProfileRoot(managed.root, release, create: true);
    final system = await _managedDirectory(profile, 'system', create: true);
    try {
      await _verifyFirmware(profile, system);
      return canPublish();
    } on Ps3OnlineIssue catch (issue) {
      if (issue != Ps3OnlineIssue.firmware) rethrow;
    }
    if (await _firmwareLibrary(system).exists()) throw Ps3OnlineIssue.firmware;
    await _checkFirmwareSearchPath(system);
    final source = File(p.join(managed.systemPath, ManagedRetro.ps3FirmwareName));
    return _publishManagedFile(managed.root, release, ['system'], ManagedRetro.ps3FirmwareName, canPublish, (
      file,
    ) async {
      if (await ManagedRetro.isVerifiedPs3FirmwarePackage(source)) {
        await source.copy(file.path);
        if (!await ManagedRetro.isVerifiedPs3FirmwarePackage(file)) throw Ps3OnlineIssue.firmware;
      } else if (canPublish()) {
        final cancel = DownloadCancel();
        await ManagedRetro.downloadPs3FirmwarePackage(
          file.path,
          progress: (received, total) {
            if (!canPublish()) {
              cancel.cancel();
            } else {
              progress(received, total);
            }
          },
          cancel: cancel,
        );
      }
    });
  }

  static Future<bool> _publishManagedFile(
    String managedRoot,
    Ps3OnlineRelease release,
    List<String> directories,
    String name,
    bool Function() canPublish,
    Future<void> Function(File) prepare,
  ) async {
    if (!canPublish()) return false;
    final profile = await managedProfileRoot(managedRoot, release, create: true);
    var directory = profile;
    for (final component in directories) {
      directory = await _managedDirectory(directory, component, create: true);
    }
    final destination = p.join(directory, name);
    final stage = await Directory(directory).createTemp('.online-import-');
    try {
      final type = await FileSystemEntity.type(destination, followLinks: false);
      if (type != FileSystemEntityType.notFound &&
          (type != FileSystemEntityType.file ||
              !p.equals(await File(destination).resolveSymbolicLinks(), destination))) {
        throw Ps3OnlineIssue.storage;
      }
      if (!canPublish()) return false;
      final file = File(p.join(stage.path, name));
      await prepare(file);
      if (!canPublish()) return false;
      await file.rename(destination);
      return true;
    } finally {
      try {
        await stage.delete(recursive: true);
      } on FileSystemException {
        // A lock on the disposable stage must not hide the import result.
      }
    }
  }

  static Future<String> _managedDirectory(String parent, String name, {required bool create}) async {
    final path = p.join(parent, name);
    final type = await FileSystemEntity.type(path, followLinks: false);
    if (create && type == FileSystemEntityType.notFound) {
      await Directory(path).create();
    } else if (type != FileSystemEntityType.directory) {
      throw Ps3OnlineIssue.storage;
    }
    if (!p.equals(await _directory(path), path)) throw Ps3OnlineIssue.storage;
    return path;
  }

  static Future<List<int>> _readProtection(File file, String digest) async {
    final bytes = await _readBounded(file, 1024 * 1024, Ps3OnlineIssue.patch);
    if (sha256.convert(bytes).toString() == digest) return bytes;
    throw Ps3OnlineIssue.patch;
  }

  static Future<List<int>> _readBounded(File file, int limit, Ps3OnlineIssue issue) async {
    try {
      final opened = await file.open();
      final List<int> bytes;
      try {
        bytes = await opened.read(limit + 1);
      } finally {
        await opened.close();
      }
      if (bytes.isNotEmpty && bytes.length <= limit) return bytes;
    } on FileSystemException {
      throw issue;
    }
    throw issue;
  }

  Map<String, Object> get networkArguments => {
    'xfloat': release.xfloat.name,
    'dns': release.dns.address,
    'upnp': release.upnp,
    'patchProtection': ?_patchProtection,
  };

  Future<void> revalidate() async {
    final current = await verify(
      provider: release.provider,
      disc: disc,
      core: core,
      onlineRoot: p.dirname(systemRoot),
      offlineSystemRoot: _offlineSystemRoot,
      releases: [release],
    );
    if (!p.equals(current.systemRoot, systemRoot)) throw Ps3OnlineIssue.storage;
    if (jsonEncode(current._patchProtection) != jsonEncode(_patchProtection)) throw Ps3OnlineIssue.patch;
  }

  static Future<Ps3OnlineProfile> verify({
    required String provider,
    required String disc,
    required String core,
    required String onlineRoot,
    required String offlineSystemRoot,
    Iterable<Ps3OnlineRelease> releases = Ps3OnlineRelease.catalog,
    ({Ps3UpdateChain chain, String root})? preparedUpdate,
  }) async {
    final discMetadata = _onlineDiscMetadata(disc);
    final title = discMetadata?['TITLE_ID'];
    if (title == null) throw Ps3OnlineIssue.unqualified;
    final release = releases.where((entry) => entry.provider == provider && entry.titleId == title).firstOrNull;
    if (release == null) throw Ps3OnlineIssue.unqualified;
    final profileRoot = await _directory(onlineRoot);
    final offlineRoot = await _directory(offlineSystemRoot);
    final systemRoot = p.join(profileRoot, 'system');
    final saveRoot = p.join(profileRoot, 'saves');
    final rpcs3Root = p.join(systemRoot, 'rpcs3');
    final configRoot = Platform.isWindows ? p.join(rpcs3Root, 'config') : rpcs3Root;
    if (_overlap(profileRoot, offlineRoot) ||
        !p.equals(await _directory(systemRoot), systemRoot) ||
        !p.equals(await _directory(rpcs3Root), rpcs3Root) ||
        !p.equals(await _directory(configRoot), configRoot)) {
      throw Ps3OnlineIssue.storage;
    }
    if (await FileSystemEntity.type(saveRoot, followLinks: false) != FileSystemEntityType.notFound &&
        !p.equals(await _directory(saveRoot), saveRoot)) {
      throw Ps3OnlineIssue.storage;
    }
    // A VFS override can redirect game and save files outside the profile.
    if (configRoot != rpcs3Root &&
        await FileSystemEntity.type(p.join(rpcs3Root, 'vfs.yml'), followLinks: false) !=
            FileSystemEntityType.notFound) {
      throw Ps3OnlineIssue.storage;
    }
    await _verifyVfs(File(p.join(configRoot, 'vfs.yml')), '$systemRoot/rpcs3/');
    try {
      await for (final item in Directory(profileRoot).list(recursive: true, followLinks: false)) {
        if (item is Link) throw Ps3OnlineIssue.storage;
      }
    } on FileSystemException {
      throw Ps3OnlineIssue.storage;
    }

    await _verifyHash(File(core), release.coreSha256, Ps3OnlineIssue.core);
    final hdd = p.join(rpcs3Root, 'dev_hdd0');
    final update = p.join(hdd, 'game', title);
    Future<void> verifyUpdate() async {
      final metadata = await _profileFile(profileRoot, p.join(update, 'PARAM.SFO'), Ps3OnlineIssue.update);
      final fields = Ps3Disc.readSfo(metadata);
      if (fields?['TITLE_ID'] != title || fields?['APP_VER'] != release.updateVersion) throw Ps3OnlineIssue.update;
      final executable = await _profileFile(profileRoot, p.join(update, 'USRDIR', 'EBOOT.BIN'), Ps3OnlineIssue.update);
      await _verifyHash(executable, release.executableSha256, Ps3OnlineIssue.update);
      if (release.updateTreeDigest case final digest?) {
        try {
          if (await ps3UpdateTreeDigest(Directory(update), generatedFiles: release.generatedUpdateFiles) != digest) {
            throw Ps3OnlineIssue.update;
          }
        } on FormatException {
          throw Ps3OnlineIssue.update;
        } on FileSystemException {
          throw Ps3OnlineIssue.update;
        }
      }
    }

    final prepare =
        preparedUpdate != null &&
        await FileSystemEntity.type(update, followLinks: false) == FileSystemEntityType.notFound;
    if (!prepare) await verifyUpdate();
    Map<String, Object>? patchProtection;
    switch (release.protection) {
      case Ps3SprxProtection(:final name, :final sha256):
        if (!RegExp(r'^[A-Za-z0-9._-]+\.sprx$').hasMatch(name)) throw Ps3OnlineIssue.unqualified;
        final patch = await _profileFile(profileRoot, p.join(hdd, 'plugins', name), Ps3OnlineIssue.patch);
        await _verifyHash(patch, sha256, Ps3OnlineIssue.patch);
      case final Ps3YamlProtection protection:
        patchProtection = await _verifyYamlProtection(profileRoot, rpcs3Root, release, protection);
    }
    for (final entry in release.providerFiles.entries) {
      final parts = entry.key.split('/');
      if (parts.any((part) => part == '.' || part == '..' || !RegExp(r'^[A-Za-z0-9_.-]+$').hasMatch(part))) {
        throw Ps3OnlineIssue.unqualified;
      }
      final file = await _profileFile(profileRoot, p.joinAll([hdd, ...parts]), Ps3OnlineIssue.patch);
      await _verifyHash(file, entry.value, Ps3OnlineIssue.patch);
    }
    await _verifyFirmware(profileRoot, systemRoot);
    final account = await _profileFile(profileRoot, p.join(configRoot, 'rpcn.yml'), Ps3OnlineIssue.account);
    await _readAccount(account, release.rpcnHost);
    if (prepare) {
      final (:chain, :root) = preparedUpdate;
      final treeDigest = release.updateTreeDigest;
      if (treeDigest == null ||
          chain.titleId != title ||
          chain.discVersion != discMetadata?['APP_VER'] ||
          chain.version != release.updateVersion ||
          chain.executableDigest != release.executableSha256) {
        throw Ps3OnlineIssue.update;
      }
      try {
        await chain.provision(root, rpcs3Root, treeDigest);
      } on FormatException {
        throw Ps3OnlineIssue.update;
      } on FileSystemException {
        throw Ps3OnlineIssue.update;
      }
      await verifyUpdate();
    }
    return Ps3OnlineProfile._(
      release,
      p.absolute(disc),
      p.absolute(core),
      systemRoot,
      saveRoot,
      offlineSystemRoot,
      patchProtection,
    );
  }

  static Future<Map<String, Object>> _verifyYamlProtection(
    String profileRoot,
    String rpcs3Root,
    Ps3OnlineRelease release,
    Ps3YamlProtection protection,
  ) async {
    final specs = Map<String, int>.of(protection.patches);
    if (!RegExp(r'^PPU-[a-f0-9]{40}$').hasMatch(protection.ppuHash) ||
        specs.isEmpty ||
        specs.length > 8 ||
        specs.entries.any(
          (entry) => !RegExp(r'^[A-Za-z0-9 ._()-]{1,96}$').hasMatch(entry.key) || entry.value < 1 || entry.value > 4096,
        )) {
      throw Ps3OnlineIssue.unqualified;
    }
    try {
      final patches = p.join(rpcs3Root, 'patches');
      if (await FileSystemEntity.type(p.join(patches, 'imported_patch.yml'), followLinks: false) !=
          FileSystemEntityType.notFound) {
        throw Ps3OnlineIssue.patch;
      }
      final base = p.join(patches, 'patch.yml');
      if (await FileSystemEntity.type(base, followLinks: false) != FileSystemEntityType.notFound) {
        final digest = protection.basePatchSha256;
        if (digest == null) throw Ps3OnlineIssue.patch;
        final file = await _profileFile(profileRoot, base, Ps3OnlineIssue.patch);
        await _verifyHash(file, digest, Ps3OnlineIssue.patch);
      }
      final file = await _profileFile(
        profileRoot,
        p.join(patches, '${release.titleId}_patch.yml'),
        Ps3OnlineIssue.patch,
      );
      final bytes = await _readProtection(file, protection.sha256);
      final yaml = loadYaml(utf8.decode(bytes));
      if (yaml is! YamlMap ||
          yaml.length != 2 ||
          _yamlScalarText(yaml.nodes['Version']) != '1.2' ||
          yaml[protection.ppuHash] is! YamlMap) {
        throw Ps3OnlineIssue.patch;
      }
      final definitions = yaml[protection.ppuHash] as YamlMap;
      if (definitions.length != specs.length) throw Ps3OnlineIssue.patch;
      final requirements = <Map<String, Object>>[];
      final options = <String>{};
      for (final MapEntry(key: name, value: writes) in specs.entries) {
        final definition = definitions[name];
        if (definition is! YamlMap ||
            definition['Games'] is! YamlMap ||
            definition['Patch'] is! YamlList ||
            (definition['Patch'] as YamlList).length != writes) {
          throw Ps3OnlineIssue.patch;
        }
        final games = definition['Games'] as YamlMap;
        final versions = games.values.whereType<YamlMap>().map((game) => game[release.titleId]).whereType<YamlList>();
        if (versions.length != 1 ||
            !versions.single.nodes.any((node) => _yamlScalarText(node) == release.updateVersion)) {
          throw Ps3OnlineIssue.patch;
        }
        final option = _patchOption(release.titleId, name);
        if (!options.add(option)) throw Ps3OnlineIssue.unqualified;
        requirements.add(Map.unmodifiable({'name': name, 'writes': writes, 'option': option}));
      }
      return Map.unmodifiable({
        'sha256': protection.sha256,
        'titleId': release.titleId,
        'updateVersion': release.updateVersion,
        'ppuHash': protection.ppuHash,
        'patches': List.unmodifiable(requirements),
      });
    } on FileSystemException {
      throw Ps3OnlineIssue.patch;
    } on FormatException {
      throw Ps3OnlineIssue.patch;
    }
  }

  // RPCS3 compares scalar text. Dart's numeric values collapse 1.20 and 1.2.
  static String? _yamlScalarText(YamlNode? node) =>
      node is YamlScalar ? (node.value is String ? node.value as String : node.span.text) : null;

  // Matches the pinned RPCS3 Libretro Patch Manager's FNV-1a option key.
  static String _patchOption(String serial, String description) {
    var hash = 0x811c9dc5;
    for (final byte in utf8.encode('$serial\x1fp$description')) {
      hash = ((hash ^ byte) * 0x01000193) & 0xffffffff;
    }
    return 'rpcs3_zpatch_${hash.toRadixString(16).padLeft(8, '0')}';
  }

  static bool _overlap(String first, String second) =>
      p.equals(first, second) || p.isWithin(first, second) || p.isWithin(second, first);

  static File _firmwareLibrary(String system) =>
      File(p.join(system, 'rpcs3', 'dev_flash', 'sys', 'external', 'liblv2.sprx'));

  static Future<void> _checkFirmwareSearchPath(String system) async {
    // The core checks system/rpcs3 before the managed package in system.
    final emulator = Directory(p.join(system, 'rpcs3'));
    if (await emulator.exists()) {
      await for (final entry in emulator.list(followLinks: false)) {
        if (p.basename(entry.path).toUpperCase() == ManagedRetro.ps3FirmwareName) {
          throw Ps3OnlineIssue.firmware;
        }
      }
    }
    await for (final entry in Directory(system).list(followLinks: false)) {
      final name = p.basename(entry.path);
      if (name.toUpperCase() == ManagedRetro.ps3FirmwareName && name != ManagedRetro.ps3FirmwareName) {
        throw Ps3OnlineIssue.firmware;
      }
    }
  }

  static Future<void> _verifyFirmware(String profile, String system) async {
    final library = _firmwareLibrary(system);
    if (await library.exists()) {
      await _profileFile(profile, library.path, Ps3OnlineIssue.firmware);
      await _profileFile(
        profile,
        p.join(system, 'rpcs3', 'dev_flash', 'vsh', 'module', 'vsh.self'),
        Ps3OnlineIssue.firmware,
      );
      return;
    }
    await _checkFirmwareSearchPath(system);
    final package = await _profileFile(profile, p.join(system, ManagedRetro.ps3FirmwareName), Ps3OnlineIssue.firmware);
    if (!await ManagedRetro.isVerifiedPs3FirmwarePackage(package)) throw Ps3OnlineIssue.firmware;
  }

  /// Accept the layout written by the pinned core after its first boot.
  static Future<void> _verifyVfs(File file, String emulatorDirectory) async {
    const mounts = {
      '/dev_hdd0/': r'$(EmulatorDir)dev_hdd0/',
      '/dev_hdd1/': r'$(EmulatorDir)dev_hdd1/',
      '/dev_flash/': r'$(EmulatorDir)dev_flash/',
      '/dev_flash2/': r'$(EmulatorDir)dev_flash2/',
      '/dev_flash3/': r'$(EmulatorDir)dev_flash3/',
      '/dev_bdvd/': r'$(EmulatorDir)dev_bdvd/',
      '/games/': r'$(EmulatorDir)games/',
      '/app_home/': '',
    };
    try {
      final type = await FileSystemEntity.type(file.path, followLinks: false);
      if (type == FileSystemEntityType.notFound) return;
      if (type != FileSystemEntityType.file || await file.length() > 16384) throw Ps3OnlineIssue.storage;
      if (loadYaml(await file.readAsString()) case final YamlMap config) {
        final directory = config[r'$(EmulatorDir)'];
        final usb = config['/dev_usb***/'];
        final device = usb is YamlMap && usb.length == 1 ? usb['/dev_usb000'] : null;
        if (config.length == mounts.length + 2 &&
            directory == emulatorDirectory &&
            mounts.entries.every((mount) => config[mount.key] == mount.value) &&
            device is YamlMap &&
            device.length == 4 &&
            device['Path'] == r'$(EmulatorDir)dev_usb000/' &&
            device['Serial'] == '' &&
            device['VID'] == '' &&
            device['PID'] == '') {
          return;
        }
      }
    } on YamlException {
      throw Ps3OnlineIssue.storage;
    } on FormatException {
      throw Ps3OnlineIssue.storage;
    } on FileSystemException {
      throw Ps3OnlineIssue.storage;
    }
    throw Ps3OnlineIssue.storage;
  }

  static Future<String> _directory(String path) async {
    try {
      final directory = Directory(path);
      if (p.isAbsolute(path) && await directory.exists()) return await directory.resolveSymbolicLinks();
    } on FileSystemException {
      throw Ps3OnlineIssue.storage;
    }
    throw Ps3OnlineIssue.storage;
  }

  static Future<File> _profileFile(String root, String path, Ps3OnlineIssue issue) async {
    try {
      final file = File(path);
      if (p.isWithin(root, await file.resolveSymbolicLinks()) && await file.length() > 0) return file;
    } on FileSystemException {
      throw issue;
    }
    throw issue;
  }

  static Future<void> _verifyHash(File file, String expected, Ps3OnlineIssue issue) async {
    try {
      if ((await sha256.bind(file.openRead()).first).toString() == expected) return;
    } on FileSystemException {
      throw issue;
    }
    throw issue;
  }

  static Future<Map<String, Object>> _readAccount(File file, String host) async {
    try {
      final bytes = await _readBounded(file, 65536, Ps3OnlineIssue.account);
      if (loadYaml(utf8.decode(bytes)) case final YamlMap account
          when _yamlScalarText(account.nodes['Version']) == '2' &&
              account['Host'] == host &&
              _nonempty(account['NPID']) &&
              _nonempty(account['Password']) &&
              (!account.containsKey('Token') || _accountString(account['Token']))) {
        return {
          'Version': 2,
          'Host': host,
          'NPID': account['NPID'] as String,
          'Password': account['Password'] as String,
          'Token': (account['Token'] as String?) ?? '',
        };
      }
    } on FormatException {
      // Parser diagnostics may contain credential values.
      throw Ps3OnlineIssue.account;
    }
    throw Ps3OnlineIssue.account;
  }

  static bool _accountString(Object? value) => value is String && !value.contains('\u0000');

  static bool _nonempty(Object? value) => _accountString(value) && (value as String).trim().isNotEmpty;
